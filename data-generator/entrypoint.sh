#!/bin/bash
# ─────────────────────────────────────────────────────────────
# entrypoint.sh
# 컨테이너 시작 시 실행되는 진입점 스크립트
#
# 1) 최초 실행: 즉시 HTML 생성 (cron 첫 주기를 기다리지 않음)
# 2) cron 데몬 시작: 이후 5분마다 자동 갱신
# 3) 로그 tail: 컨테이너 로그에 cron 실행 결과 출력
# ─────────────────────────────────────────────────────────────

set -e

echo "============================================"
echo "  🌍 Weather Dashboard — Data Generator"
echo "============================================"
echo "[$(date '+%Y-%m-%d %H:%M:%S')] 컨테이너 시작"

# 로그 파일 초기화
LOG_FILE="/var/log/cron.log"
touch "$LOG_FILE"

# ── 1. 즉시 최초 실행 ───────────────────────────
echo "[$(date '+%Y-%m-%d %H:%M:%S')] 최초 HTML 생성 중..."
cd /app
python fetch_data.py
echo "[$(date '+%Y-%m-%d %H:%M:%S')] 최초 HTML 생성 완료 ✓"

# ── 2. cron 데몬 시작 ───────────────────────────
echo "[$(date '+%Y-%m-%d %H:%M:%S')] cron 데몬 시작 (매 5분마다 갱신)"
service cron start

# ── 3. 로그를 포어그라운드로 출력 (컨테이너 유지) ──
echo "[$(date '+%Y-%m-%d %H:%M:%S')] 로그 모니터링 시작..."
echo "--------------------------------------------"
tail -F "$LOG_FILE"
